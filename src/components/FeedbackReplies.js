/**
 * FeedbackReplies component.
 *
 * Renders the reply thread under an AI Feedback note: existing user and AI
 * replies plus, while an AI reply is being generated, a pending row that
 * polls /replies/{id}/status for completion.
 */
import { __, sprintf } from '@wordpress/i18n';
import { Spinner } from '@wordpress/components';
import { speak } from '@wordpress/a11y';
import { useEffect, useRef } from '@wordpress/element';
import useReplyStatus from '../hooks/useReplyStatus';

/**
 * @typedef {Object} Reply
 * @property {number|string} id      Comment ID.
 * @property {string}        author  Author name.
 * @property {string}        content Reply body. Plain text, rendered as a text node, never HTML.
 * @property {boolean}       is_ai   Whether this reply was generated by AI Feedback.
 */

/**
 * @param {Object}      props
 * @param {Reply[]}     props.replies           Existing replies in the thread, oldest first.
 * @param {number|null} [props.pendingReplyId]  User reply whose AI response is being generated.
 * @param {Function}    [props.onReplyComplete] Called once the pending AI reply has been saved.
 * @return {Element|null} The reply thread, or `null` when there is nothing to show.
 */
export default function FeedbackReplies({
	replies = [],
	pendingReplyId = null,
	onReplyComplete,
}) {
	const { status } = useReplyStatus(pendingReplyId);
	const hasPendingSlot = Boolean(pendingReplyId);
	const isPolling =
		hasPendingSlot && status !== 'complete' && status !== 'failed';
	const hasFailed = hasPendingSlot && status === 'failed';

	useEffect(() => {
		if (hasPendingSlot && status === 'complete') {
			onReplyComplete?.();
		}
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [pendingReplyId, hasPendingSlot, status]);

	// Announce AI replies that arrive after the thread first rendered.
	const announcedRef = useRef(null);
	useEffect(() => {
		const aiReplies = replies.filter((reply) => reply.is_ai);
		if (announcedRef.current === null) {
			announcedRef.current = new Set(aiReplies.map((reply) => reply.id));
			return;
		}
		aiReplies
			.filter((reply) => !announcedRef.current.has(reply.id))
			.forEach((reply) => {
				announcedRef.current.add(reply.id);
				speak(
					sprintf(
						/* translators: %s: AI reply text. */
						__('AI Feedback replied: %s', 'ai-feedback'),
						reply.content
					)
				);
			});
	}, [replies]);

	if (replies.length === 0 && !hasPendingSlot) {
		return null;
	}

	const isSlotEmpty = !isPolling && !hasFailed;

	return (
		<ul
			className="ai-feedback-replies"
			aria-label={__('Conversation replies', 'ai-feedback')}
		>
			{replies.map((reply) => (
				<li
					key={reply.id}
					className={
						'ai-feedback-reply' +
						(reply.is_ai
							? ' ai-feedback-reply-ai'
							: ' ai-feedback-reply-user')
					}
				>
					<span className="ai-feedback-reply-author">
						{reply.is_ai
							? __('AI Feedback', 'ai-feedback')
							: reply.author}
					</span>
					<span className="ai-feedback-reply-content">
						{reply.content}
					</span>
				</li>
			))}

			{/*
			 * Screen readers only announce changes inside a live region that is
			 * already in the DOM, so this row stays mounted for the whole
			 * pending lifecycle and only its content changes.
			 */}
			{hasPendingSlot && (
				<li
					className="ai-feedback-reply ai-feedback-reply-pending"
					aria-live="polite"
					aria-atomic="true"
					aria-hidden={isSlotEmpty ? true : undefined}
				>
					{isPolling && (
						<>
							<Spinner />
							<span className="ai-feedback-reply-content">
								{__('AI is replying…', 'ai-feedback')}
							</span>
						</>
					)}
					{hasFailed && (
						<span className="ai-feedback-reply-content ai-feedback-reply-error">
							{__(
								'The AI reply could not be generated. Reply again to retry.',
								'ai-feedback'
							)}
						</span>
					)}
				</li>
			)}
		</ul>
	);
}
