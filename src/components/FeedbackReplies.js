/**
 * FeedbackReplies component.
 *
 * Renders the reply thread under an AI Feedback note: existing user and AI
 * replies plus, while an AI reply is being generated, a pending row that
 * polls /replies/{id}/status for completion and offers a retry when the
 * reply is slow or fails. An AI reply that proposes an edit to the note's
 * block shows it with Preview and Apply, or its suggestion status once it is
 * a Gutenberg suggestion. Each edit is labeled with its revision, and only
 * the newest can be applied. Quick replies follow the latest AI message.
 */
import { __, sprintf } from '@wordpress/i18n';
import { Button, Spinner } from '@wordpress/components';
import { speak } from '@wordpress/a11y';
import { useEffect, useRef } from '@wordpress/element';
import useReplyStatus from '../hooks/useReplyStatus';
import QuickFix from './QuickFix';
import BlockAction from './BlockAction';
import QuickReplies from './QuickReplies';
import { isBlockAction, isReplyEdit } from '../utils/is-reply-edit';
import { getRevisionLabel, getSupersededOwnerIds } from '../utils/revisions';

/**
 * @typedef {Object} Reply
 * @property {number|string} id         Comment ID.
 * @property {string}        author     Author name.
 * @property {string}        content    Reply body. Plain text, rendered as a text node, never HTML.
 * @property {boolean}       is_ai      Whether this reply was generated by AI Feedback.
 * @property {Object|null}   [edit]     Change an AI reply proposes for the note's block.
 * @property {number|null}   [revision] Which revision of the thread's suggested edit `edit` is.
 */

/**
 * @param {Object}      props
 * @param {Reply[]}     props.replies           Existing replies in the thread, oldest first.
 * @param {number|null} [props.pendingReplyId]  User reply whose AI response is being generated.
 * @param {Function}    [props.onReplyComplete] Called once the pending AI reply has been saved.
 * @param {Object}      [props.note]            The thread's note, with `id` and `block_id`. Edits are shown only when given.
 *                                              `is_mention` marks a thread a person started, whose answer
 *                                              is requested with the editor's content.
 * @return {Element|null} The reply thread, or `null` when there is nothing to show.
 */
export default function FeedbackReplies({
	replies = [],
	pendingReplyId = null,
	onReplyComplete,
	note = null,
}) {
	const { status, isSlow, canRetry, retry } = useReplyStatus(pendingReplyId, {
		sendContent: !!note?.is_mention,
	});
	const hasPendingSlot = Boolean(pendingReplyId);
	const isPolling =
		hasPendingSlot && status !== 'complete' && status !== 'failed';
	const hasFailed = hasPendingSlot && status === 'failed';
	const retryButton = (
		<Button
			variant="link"
			className="ai-feedback-reply-retry"
			onClick={retry}
			// The server ignores a retry right after a failed attempt.
			disabled={!canRetry}
			accessibleWhenDisabled
		>
			{__('Try again', 'fresh-eyes')}
		</Button>
	);

	useEffect(() => {
		if (hasPendingSlot && status === 'complete') {
			onReplyComplete?.();
		}
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [pendingReplyId, hasPendingSlot, status]);

	// Announce AI replies that arrive after the thread first rendered.
	// Only speak once this thread has waited on a reply, so replies that load
	// with the sidebar are not read out.
	const announcedRef = useRef(null);
	const sawPendingRef = useRef(false);
	if (hasPendingSlot) {
		sawPendingRef.current = true;
	}
	useEffect(() => {
		const aiReplies = replies.filter((reply) => reply.is_ai);
		if (announcedRef.current === null) {
			announcedRef.current = new Set(aiReplies.map((reply) => reply.id));
			return;
		}
		aiReplies
			.filter((reply) => !announcedRef.current.has(reply.id))
			.forEach((reply) => {
				announcedRef.current.add(reply.id);
				if (!sawPendingRef.current) {
					return;
				}
				speak(
					sprintf(
						/* translators: %s: AI reply text. */
						__('Fresh Eyes replied: %s', 'fresh-eyes'),
						reply.content
					)
				);
			});
	}, [replies]);

	// Quick replies follow the latest AI message: the newest AI reply, or the
	// note itself while its quick fix waits on the author.
	const lastReply = replies[replies.length - 1];
	const showQuickReplies =
		!!note?.id &&
		!!note.block_id &&
		!note.is_resolved &&
		!note.is_group &&
		!hasPendingSlot &&
		(lastReply
			? lastReply.is_ai
			: !note.parent &&
				!!(note.quick_fix || note.block_action || note.block_change));

	if (replies.length === 0 && !hasPendingSlot && !showQuickReplies) {
		return null;
	}

	const isSlotEmpty = !isPolling && !hasFailed;
	const superseded = getSupersededOwnerIds(note, replies);

	return (
		<>
			<ul
				className="ai-feedback-replies"
				aria-label={__('Conversation replies', 'fresh-eyes')}
			>
				{replies.map((reply) => (
					<li
						key={reply.id}
						className={
							'ai-feedback-reply' +
							(reply.is_ai
								? ' ai-feedback-reply-ai'
								: ' ai-feedback-reply-user')
						}
					>
						<span className="ai-feedback-reply-author">
							{reply.is_ai
								? __('Fresh Eyes', 'fresh-eyes')
								: reply.author}
						</span>
						<span className="ai-feedback-reply-content">
							{reply.content}
						</span>
						{reply.is_ai && isReplyEdit(reply.edit) && (
							<span className="ai-feedback-reply-revision">
								{getRevisionLabel(reply.revision)}
							</span>
						)}
						{reply.is_ai &&
							isBlockAction(reply.edit) &&
							note?.block_id && (
								<BlockAction
									item={note}
									action={reply.edit}
									noteId={reply.id}
									isSuperseded={superseded.includes(reply.id)}
								/>
							)}
						{reply.is_ai &&
							isReplyEdit(reply.edit) &&
							!isBlockAction(reply.edit) &&
							note?.block_id && (
								<QuickFix
									item={note}
									edit={reply.edit}
									noteId={reply.id}
									isSuperseded={superseded.includes(reply.id)}
								/>
							)}
					</li>
				))}

				{/*
				 * Screen readers only announce changes inside a live region that is
				 * already in the DOM, so this row stays mounted for the whole
				 * pending lifecycle and only its content changes.
				 */}
				{hasPendingSlot && (
					<li
						className="ai-feedback-reply ai-feedback-reply-pending"
						aria-live="polite"
						aria-atomic="true"
						aria-hidden={isSlotEmpty ? true : undefined}
					>
						{isPolling && (
							<>
								<Spinner />
								<span className="ai-feedback-reply-content">
									{isSlow
										? __(
												'This is taking longer than expected.',
												'fresh-eyes'
											)
										: __('AI is replying…', 'fresh-eyes')}
								</span>
								{isSlow && retryButton}
							</>
						)}
						{hasFailed && (
							<>
								<span className="ai-feedback-reply-content ai-feedback-reply-error">
									{__(
										'The AI reply could not be generated.',
										'fresh-eyes'
									)}
								</span>
								{retryButton}
								{!canRetry && (
									<span className="ai-feedback-reply-retry-hint">
										{__(
											'Try again in a few seconds.',
											'fresh-eyes'
										)}
									</span>
								)}
							</>
						)}
					</li>
				)}
			</ul>
			{showQuickReplies && <QuickReplies note={note} replies={replies} />}
		</>
	);
}
